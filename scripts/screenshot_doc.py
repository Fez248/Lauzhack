#!/usr/bin/env python3
"""Build a browsable screenshot doc (README.md + images) from the PNGs the jvm tests render.

    python3 scripts/screenshot_doc.py shared/build/screenshots out/screenshots [--sha abc1234]

The input folder is `shared/build/screenshots/` after `./gradlew :shared:jvmTest`. The output
folder gets `README.md` and `img/*.png`. Used by `.github/workflows/screenshots.yml`; also works
locally. Standard library only.
"""
import argparse
import datetime
import re
import shutil
from pathlib import Path

# Filename prefix → section of the doc, in display order. Written by these tests (shared/src/jvmTest):
GROUPS = [
    ("pane_", "Every pane", "One screenshot per screen of the app, through the real app shell (PanesRenderTest)."),
    ("ui-", "Click-through: guest, offline", "Real clicks through the app from the first screen (AppUiFlowTest)."),
    ("shell_", "App shell variants", "Sign-in, onboarding, home, settings… in dark mode, compact width, French (ShellScreensRenderTest)."),
    ("learn_", "Learning screens and states", "Placement, lesson sections, practice at each support level, feedback (LearnScreenshotsTest)."),
    ("gallery_", "Design system gallery", "Every component (GalleryRenderTest)."),
]
OTHER = ("", "Other", "")

# `<name>_01.png`, `<name>_02.png`… are tiles of a tall `<name>.png` (Screenshots.render): skip them.
TILE = re.compile(r"^(.+)_\d{2}$")


def title(stem: str, prefix: str) -> str:
    s = stem[len(prefix):] if prefix else stem
    s = re.sub(r"^\d+[_-]", "", s)  # ordering number (pane_01_…, ui-01-…)
    return re.sub(r"[_-]+", " ", s).strip().capitalize() or stem


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src", type=Path, help="folder with the rendered PNGs")
    ap.add_argument("out", type=Path, help="output folder (README.md + img/)")
    ap.add_argument("--sha", default="", help="commit the screenshots were rendered from")
    args = ap.parse_args()

    pngs = sorted(args.src.glob("*.png"))
    stems = {p.stem for p in pngs}
    pngs = [p for p in pngs if not ((m := TILE.match(p.stem)) and m.group(1) in stems)]
    if not pngs:
        raise SystemExit(f"no screenshots in {args.src}")

    img = args.out / "img"
    if img.exists():
        shutil.rmtree(img)
    img.mkdir(parents=True)

    sections: dict[str, list[Path]] = {g[0]: [] for g in GROUPS + [OTHER]}
    for p in pngs:
        prefix = next((g[0] for g in GROUPS if p.name.startswith(g[0])), "")
        sections[prefix].append(p)
        shutil.copy2(p, img / p.name)

    when = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    sha = f" from commit `{args.sha[:7]}`" if args.sha else ""
    lines = [
        "# ThisIsTea screenshots",
        "",
        f"Rendered off-screen by the jvm tests{sha} on {when}. {len(pngs)} screenshots.",
        "Generated by `.github/workflows/screenshots.yml`: do not edit by hand.",
        "",
        "## Contents",
        "",
    ]
    present = [g for g in GROUPS + [OTHER] if sections[g[0]]]
    for prefix, name, _intro in present:
        anchor = re.sub(r"[^a-z0-9 -]", "", name.lower()).replace(" ", "-")
        lines.append(f"- [{name}](#{anchor}) ({len(sections[prefix])})")
    for prefix, name, intro in present:
        lines += ["", f"## {name}", ""]
        if intro:
            lines += [intro, ""]
        for p in sections[prefix]:
            t = title(p.stem, prefix)
            lines += [
                f"### {t}",
                "",
                f"`{p.name}`",
                "",
                f'<a href="img/{p.name}"><img src="img/{p.name}" alt="{t}" width="380"></a>',
                "",
            ]
    (args.out / "README.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(pngs)} screenshots -> {args.out / 'README.md'}")


if __name__ == "__main__":
    main()
